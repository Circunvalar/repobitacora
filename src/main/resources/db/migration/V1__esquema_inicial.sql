CREATE TABLE cargue (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha                DATE         NOT NULL,
    hora_inicio_plan     TIME,
    hora_fin_plan        TIME,
    inicio_campana       TIMESTAMP,
    fin_campana          TIMESTAMP,
    campana_id           VARCHAR(50)  NOT NULL,
    campana_nombre       VARCHAR(200),
    tipo_marcacion       VARCHAR(20),
    nombre_lista         VARCHAR(255) NOT NULL,
    lista_base           VARCHAR(255) NOT NULL,
    archivo              VARCHAR(255) NOT NULL,
    huella               VARCHAR(64),
    estrategia           VARCHAR(20)  NOT NULL,
    remarcacion          INT          NOT NULL DEFAULT 0,
    jefe                 VARCHAR(150),
    nombre_estrategia    VARCHAR(255),
    observacion          VARCHAR(1000),
    registros_archivo    INT          NOT NULL DEFAULT 0,
    registros_no_validos INT          NOT NULL DEFAULT 0,
    registros_cargados   INT          NOT NULL DEFAULT 0,
    rechazados_wolkvox   INT          NOT NULL DEFAULT 0,
    total_gestionado     INT,
    archivo_rechazados   VARCHAR(500),
    descarga_informe     VARCHAR(5)   NOT NULL DEFAULT 'PDT',
    estado               VARCHAR(30)  NOT NULL,
    inicio_cargue        TIMESTAMP,
    fin_cargue           TIMESTAMP,
    error                VARCHAR(1000),
    creado               TIMESTAMP    NOT NULL
);
CREATE INDEX ix_cargue_fecha ON cargue (fecha);
CREATE INDEX ix_cargue_campana_lista ON cargue (campana_id, lista_base);
CREATE INDEX ix_cargue_huella ON cargue (huella);

CREATE TABLE corte_hora (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campana_id         VARCHAR(50) NOT NULL,
    hora               TIMESTAMP   NOT NULL,
    agentes_conectados INT         NOT NULL DEFAULT 0,
    registros_barridos INT         NOT NULL DEFAULT 0,
    gestionados        INT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_corte_hora UNIQUE (campana_id, hora)
);

CREATE TABLE evento_campana (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campana_id VARCHAR(50) NOT NULL,
    tipo       VARCHAR(20) NOT NULL,
    momento    TIMESTAMP   NOT NULL,
    origen     VARCHAR(20) NOT NULL
);
