-- Encendidos programados: solo para el día en que se programan (cada día se sube una base nueva).
CREATE TABLE programacion (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion_id  BIGINT       NOT NULL REFERENCES operacion(id),
    campana_id    VARCHAR(50)  NOT NULL,
    fecha         DATE         NOT NULL,
    hora          TIME         NOT NULL,
    cargue_id     BIGINT,
    estado        VARCHAR(20)  NOT NULL,
    ejecutada     TIMESTAMP,
    error         VARCHAR(1000),
    creado        TIMESTAMP    NOT NULL
);
CREATE INDEX ix_programacion_fecha ON programacion(fecha, estado);
