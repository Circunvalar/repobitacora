-- Campañas principales: cada una con su servidor de Wolkvox y su token
CREATE TABLE operacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(150)  NOT NULL,
    servidor          VARCHAR(20)   NOT NULL,
    token             VARCHAR(500)  NOT NULL,
    archivada         BOOLEAN       NOT NULL DEFAULT FALSE,
    token_valido      BOOLEAN,
    campanas_servidor INT,
    ultima_validacion TIMESTAMP,
    ultimo_error      VARCHAR(1000),
    ultimo_escaneo    TIMESTAMP,
    creado            TIMESTAMP     NOT NULL,
    CONSTRAINT uq_operacion_nombre UNIQUE (nombre)
);

-- Números de campaña de Wolkvox registrados a mano dentro de cada campaña principal (para futuros cargues)
DROP TABLE campana_estado;
CREATE TABLE campana (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion_id    BIGINT        NOT NULL REFERENCES operacion (id),
    campana_id      VARCHAR(50)   NOT NULL,
    nombre          VARCHAR(200),
    tipo            VARCHAR(20),
    activa          BOOLEAN,
    registros       INT,
    desde           TIMESTAMP,
    ultima_revision TIMESTAMP,
    ultimo_error    VARCHAR(1000),
    creado          TIMESTAMP     NOT NULL,
    CONSTRAINT uq_campana UNIQUE (operacion_id, campana_id)
);

