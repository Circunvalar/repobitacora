ALTER TABLE cargue ADD COLUMN operacion_nombre VARCHAR(150);
ALTER TABLE evento_campana ADD COLUMN operacion_id BIGINT;
ALTER TABLE evento_campana ADD COLUMN operacion_nombre VARCHAR(150);
ALTER TABLE corte_hora ADD COLUMN operacion_id BIGINT;
ALTER TABLE corte_hora DROP CONSTRAINT uq_corte_hora;
ALTER TABLE corte_hora ADD CONSTRAINT uq_corte_hora UNIQUE (operacion_id, campana_id, hora);
